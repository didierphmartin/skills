#!/usr/bin/env python3
"""Dev-only: regenerate references/example-customer-portal.md from the test fixtures (the description in English
and French, the two specs, and every file create.py writes for AWS and Azure), so the example never drifts.
Usage: python3 dev/build_example.py [--check]   (--check exits 1 when the file is out of date)
"""
import argparse, importlib.util, json, sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
FIX = SKILL / 'tests' / 'fixtures'
TARGET = SKILL / 'references' / 'example-customer-portal.md'
FENCE = {'.tf': 'hcl', '.json': 'json', '.example': 'hcl', '.md': 'markdown', '.gitignore': 'text'}


def load_create():
    spec = importlib.util.spec_from_file_location('create', SKILL / 'scripts' / 'create.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def fence(name: str) -> str:
    return next((v for k, v in FENCE.items() if name.endswith(k)), 'text')


def build() -> str:
    create = load_create()
    catalog = create.load_catalog()
    en = json.loads((FIX / 'customer-portal.json').read_text(encoding='utf-8'))
    fr = json.loads((FIX / 'customer-portal-fr.json').read_text(encoding='utf-8'))
    out = ['# Example — customer portal (maintainers)', '',
           'Generated by `dev/build_example.py` from `tests/fixtures/customer-portal*`; do not edit by hand.', '',
           '## The description (English)', '', '```text', (FIX / 'customer-portal-en.txt').read_text(encoding='utf-8').rstrip(), '```', '',
           '## The description (French)', '', '```text', (FIX / 'customer-portal-fr.txt').read_text(encoding='utf-8').rstrip(), '```', '',
           '## The spec (English)', '', '"portal.example.com" is a custom domain: out of v1, so it is in `left_out` and the '
           'reply says so.', '', '```json', json.dumps(en, indent=2, ensure_ascii=False), '```', '',
           '## The spec (French)', '', 'Only `title` and the placeholder description change: names, options and edges are the same.', '',
           '```json', json.dumps(fr, indent=2, ensure_ascii=False), '```', '']
    for cloud in ('aws', 'azure'):
        spec = create.Spec(en, catalog, cloud, None)
        if spec.errors or spec.need_target:
            print(f'build_example: the customer-portal spec is invalid for {cloud}: {spec.errors or "needs a target"}')
            sys.exit(1)
        project = create.project_for(spec)
        files = project.files()
        out += [f'## Generated for {project.cloud_title} ({spec.region})', '']
        for name, text in files.items():
            if name in ('README.md', 'spec.json'):
                continue
            out += [f'### `{name}`', '', f'```{fence(name)}', text.rstrip(), '```', '']
    return '\n'.join(out).rstrip() + '\n'


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = build()
    if a.check:
        current = TARGET.read_text(encoding='utf-8') if TARGET.is_file() else ''
        if current != text:
            print(f'{TARGET} is out of date: run python3 dev/build_example.py')
            return 1
        print('up to date')
        return 0
    TARGET.write_text(text, encoding='utf-8')
    print(f'wrote {TARGET}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
