#!/usr/bin/env python3
"""Dev-only: regenerate references/example-onboarding.md from the test fixtures (procedure text EN/FR,
the two specs, and the flow create.py renders for the English spec), so the example never drifts.
Usage: python3 dev/build_example.py [--check]   (--check exits 1 when the file is out of date)
"""
import argparse, copy, importlib.util, json, sys
from pathlib import Path

SKILL = Path(__file__).resolve().parents[1]
FIX = SKILL / 'tests' / 'fixtures'
OUT = SKILL / 'references' / 'example-onboarding.md'
MAPPING = [
    ("When HR creates a new user record for an employee who hasn't started yet, start the onboarding",
     'trigger `service_catalog`: HR orders the onboarding catalog item right after creating the user; the sentence becomes '
     '`form.submitted_by` (the catalog item\'s description and "Who submits this form and when" in FLOWS.md)'),
    ('What the steps need to know (order form)', '`form.variables`: new hire, manager, department (reference), start date (date), '
     'equipment (list_collector on `cmdb_model`), first-day information (multi_line_text)'),
    ("ask the new hire's manager to approve the onboarding and confirm the equipment list",
     '`askForApproval` on the requested item (`trigger.request_item`, `sc_req_item`), approver `form.manager`: the manager '
     'approves the request that carries the equipment list'),
    ('If the manager rejects it, notify HR with the reason and stop there',
     '`if` approval_state != approved (any outcome other than approved takes the stop path) → `sendNotification` (placeholder; the notification shows the approval comments) + `end`'),
    ('in parallel: a task for the IT service desk … a task for Facilities',
     '`parallel` with two `createCatalogTask` on the request item, `ah_wait: false`, group placeholders'),
    ('For each item on the approved equipment list … a separate hardware request task',
     'a list collector answer is a comma-separated string of sys_ids, not an array (`forEach` iterates arrays only: '
     'wfa-flow-logic-api.md:134-135), so `lookUpRecords` on `cmdb_model` with `sys_idIN` + the answer → `for_each` over '
     '`Records` → one `createCatalogTask` per item'),
    ("Send the new hire's manager an email summarising what was requested and the start date",
     '`sendEmail` to `form.manager.email`; the new hire and the start date go in the subject (an email body takes no pills: '
     'action-api.md:256), the body lists what was requested'),
    ('Two working days before the start date, check … remind the assignment groups',
     '`wait_duration` 2 days `before` `form.start_date` with a `working_days_schedule` placeholder → `lookUpRecords` open '
     '`sc_task` of the request item → `if` Count > 0 → `for_each` → `sendNotification`'),
    ("if they're still open on the start date, escalate to the IT manager and inform HR",
     '`wait_duration` 9 hours `after` `form.start_date` (the morning of the start date: the date alone is midnight, so 9h after is 9:00; the schedule caveat applies to every `wait_duration` with a schedule: a schedule "day" = 24h of schedule time) → `lookUpRecords` → `if` → two `sendNotification`'),
    ('welcome email with their first-day information, and log',
     '`sendNotification` (placeholder on the request item, which can show the First-day information variable; a '
     '`sendEmail` body cannot carry it), then `log`'),
]


def quote(text: str) -> str:
    return '\n'.join(('> ' + line).rstrip() for line in text.strip().splitlines())


def build() -> str:
    spec = importlib.util.spec_from_file_location('create', SKILL / 'scripts' / 'create.py')
    create = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(create)
    vocab = create.load_vocabulary()
    en = json.loads((FIX / 'onboarding-en.json').read_text(encoding='utf-8'))
    fr = json.loads((FIX / 'onboarding-fr.json').read_text(encoding='utf-8'))
    errors, ir = create.check_spec(copy.deepcopy(en), vocab)
    assert not errors, errors
    L = ['# Reference example — new employee onboarding (EN + FR)', '',
         'The procedure a user pastes, the spec you write, and the flow `create.py` generates (vendor `1234567`). '
         'Generated by `dev/build_example.py`; the build gate compiles both flows with `now-sdk build` (0 errors).', '',
         '## The procedure (English)', '', quote((FIX / 'onboarding-en.txt').read_text(encoding='utf-8')), '',
         '## The procedure (French)', '', quote((FIX / 'onboarding-fr.txt').read_text(encoding='utf-8')), '',
         '## How each sentence maps', '', '| Procedure | Spec |', '|---|---|']
    L += [f'| {a} | {b} |' for a, b in MAPPING]
    L += ['', 'Placeholders: every instance record the procedure cannot name (groups, notifications, schedules, catalog, category) is '
          'declared once in the spec\'s `placeholders` block (`kind`, `description`, optional `value`) and referenced as '
          '`{"placeholder": "<name>"}`; the generated flow carries `\'PLACEHOLDER:<name>\'` and FLOWS.md lists each one for the user to fill.', '',
          'The French spec is the same flow: same ids, variables and structure, every `label`, question, subject, body, '
          'message and placeholder `description` in French, and its own `name` (`integration-nouvel-employe`).', '',
          '## Spec (English)', '', '```json', json.dumps(en, indent=2, ensure_ascii=False), '```', '',
          '## Spec (French)', '', '```json', json.dumps(fr, indent=2, ensure_ascii=False), '```', '',
          '## Generated flow (English) — `src/fluent/flows/new-employee-onboarding.now.ts`', '', '```ts',
          create.render_flow(ir).rstrip('\n'), '```', '']
    return '\n'.join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = build()
    if a.check:
        ok = OUT.is_file() and OUT.read_text(encoding='utf-8') == text
        print('example-onboarding.md is ' + ('up to date' if ok else 'OUT OF DATE — run dev/build_example.py'))
        return 0 if ok else 1
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
